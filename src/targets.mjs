// 산출물 만들기: AsyncAPI spec 하나 → npm 패키지 · Swift Package · Android 라이브러리(Maven) · 문서
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, chmodSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { emitTs } from './emit-ts.mjs'
import { emitSwift } from './emit-swift.mjs'
import { emitKotlin } from './emit-kotlin.mjs'
import { emitDocs } from './emit-docs.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const RUNTIME = join(ROOT, 'runtime')
const require = createRequire(import.meta.url)

/** 버전 고정: 이 조합으로 PoC를 검증했다 */
export const ANDROID_VERSIONS = {
  agp: '8.10.1',
  kotlin: '2.1.20',
  serialization: '1.6.3',
  coroutines: '1.7.3',
  webkit: '1.14.0',
  compileSdk: 35,
}

const write = (path, content) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, content)
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: opts.quiet ? 'pipe' : 'inherit', encoding: 'utf8', ...opts })
  if (r.status !== 0) {
    const tail = opts.quiet ? `\n${(r.stdout ?? '').slice(-2000)}${(r.stderr ?? '').slice(-2000)}` : ''
    throw new Error(`${cmd} ${args.join(' ')} 실패 (exit ${r.status})${tail}`)
  }
  return r
}

// ── JS (npm) ─────────────────────────────────────────────────────────
export function buildJs(model, specText, out, { pack = true, log = console.log } = {}) {
  const dir = join(out, 'js')
  rmSync(dir, { recursive: true, force: true })
  write(join(dir, 'generated/contract.ts'), emitTs(model))
  for (const f of readdirSync(join(RUNTIME, 'web'))) cpSync(join(RUNTIME, 'web', f), join(dir, 'src', f))
  write(join(dir, 'asyncapi.yaml'), specText)
  const pkg = {
    name: model.config.npm.name,
    version: model.version,
    description: `${model.title} — WebView bridge client (generated by bridgegen)`,
    type: 'module',
    main: './dist/src/index.js',
    types: './dist/src/index.d.ts',
    exports: {
      '.': { types: './dist/src/index.d.ts', import: './dist/src/index.js' },
      './asyncapi.yaml': './asyncapi.yaml',
      './package.json': './package.json',
    },
    files: ['dist', 'asyncapi.yaml'],
    sideEffects: false,
    license: 'MIT',
  }
  write(join(dir, 'package.json'), JSON.stringify(pkg, null, 2) + '\n')
  write(
    join(dir, 'tsconfig.json'),
    JSON.stringify(
      {
        compilerOptions: {
          target: 'ES2020',
          module: 'ESNext',
          moduleResolution: 'Bundler',
          lib: ['ES2020', 'DOM'],
          strict: true,
          declaration: true,
          rootDir: '.',
          outDir: 'dist',
          skipLibCheck: true,
          types: [],
        },
        include: ['src', 'generated'],
      },
      null,
      2,
    ) + '\n',
  )
  write(join(dir, 'README.md'), `# ${pkg.name}\n\n${model.title} v${model.version} 웹 클라이언트. [bridgegen](https://github.com/<owner>/bridgegen)이 \`asyncapi.yaml\`에서 생성했습니다.\n\n\`\`\`ts\nimport { createBridge } from '${pkg.name}'\nconst bridge = createBridge()\n\`\`\`\n`)
  if (!pack) return { dir }
  const tsc = require.resolve('typescript/bin/tsc')
  log('  · tsc')
  run(process.execPath, [tsc, '-p', join(dir, 'tsconfig.json')], { quiet: true })
  log('  · npm pack')
  const r = run('npm', ['pack', '--silent', '--pack-destination', out], { cwd: dir, quiet: true })
  const tgz = join(out, r.stdout.trim().split('\n').pop())
  return { dir, tgz }
}

// ── iOS (Swift Package) ──────────────────────────────────────────────
export function buildIos(model, out, { verify = false, log = console.log } = {}) {
  const dir = join(out, 'ios')
  const mod = model.config.swift.module
  rmSync(dir, { recursive: true, force: true })
  write(join(dir, 'Sources', mod, 'BridgeContract.swift'), emitSwift(model))
  cpSync(join(RUNTIME, 'ios/NativeBridgeRouter.swift'), join(dir, 'Sources', mod, 'NativeBridgeRouter.swift'))
  write(
    join(dir, 'Package.swift'),
    `// swift-tools-version:5.9
// 생성: bridgegen · ${model.title} v${model.version}
import PackageDescription

let package = Package(
    name: "${mod}",
    platforms: [.iOS(.v15), .macOS(.v12)],
    products: [.library(name: "${mod}", targets: ["${mod}"])],
    targets: [.target(name: "${mod}", path: "Sources/${mod}")]
)
`,
  )
  write(join(dir, 'README.md'), `# ${mod}\n\n${model.title} v${model.version} iOS 브릿지 (Swift Package). Xcode에서 *Add Package Dependencies → Add Local…* 또는 git URL로 추가합니다.\n`)
  if (verify) {
    log('  · xcodebuild (iOS Simulator SDK)')
    run('xcodebuild', ['-scheme', mod, '-destination', 'generic/platform=iOS Simulator', '-derivedDataPath', join(out, '.build-ios'), '-quiet', 'build'], { cwd: dir, quiet: true })
    rmSync(join(out, '.build-ios'), { recursive: true, force: true })
  }
  return { dir }
}

// ── Android (Maven) ──────────────────────────────────────────────────
export function findAndroidSdk() {
  const c = [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT, join(process.env.HOME ?? '', 'Library/Android/sdk'), join(process.env.HOME ?? '', 'Android/Sdk')]
  return c.find((p) => p && existsSync(join(p, 'platforms')))
}

export function findJavaHome() {
  if (process.env.JAVA_HOME && existsSync(join(process.env.JAVA_HOME, 'bin/java'))) return process.env.JAVA_HOME
  const studio = '/Applications/Android Studio.app/Contents/jbr/Contents/Home'
  return existsSync(join(studio, 'bin/java')) ? studio : undefined
}

export function buildAndroid(model, out, { publish = true, log = console.log } = {}) {
  const dir = join(out, 'android')
  const { groupId, artifactId, package: pkg, minSdk } = model.config.android
  const V = ANDROID_VERSIONS
  rmSync(dir, { recursive: true, force: true })
  const src = join(dir, 'src/main/kotlin', ...pkg.split('.'))
  write(join(src, 'BridgeContract.kt'), emitKotlin(model))
  write(join(src, 'NativeBridgeRouter.kt'), readFileSync(join(RUNTIME, 'android/NativeBridgeRouter.kt'), 'utf8').replace('package __PACKAGE__', `package ${pkg}`))
  write(join(dir, 'src/main/AndroidManifest.xml'), '<?xml version="1.0" encoding="utf-8"?>\n<manifest />\n')
  cpSync(join(RUNTIME, 'android/wrapper'), dir, { recursive: true })
  chmodSync(join(dir, 'gradlew'), 0o755)
  write(
    join(dir, 'settings.gradle.kts'),
    `pluginManagement {
    repositories { google(); mavenCentral(); gradlePluginPortal() }
}
dependencyResolutionManagement {
    repositories { google(); mavenCentral() }
}
rootProject.name = "${artifactId}"
`,
  )
  write(
    join(dir, 'build.gradle.kts'),
    `// 생성: bridgegen · ${model.title} v${model.version}
plugins {
    id("com.android.library") version "${V.agp}"
    id("org.jetbrains.kotlin.android") version "${V.kotlin}"
    id("org.jetbrains.kotlin.plugin.serialization") version "${V.kotlin}"
    \`maven-publish\`
}

android {
    namespace = "${pkg}"
    compileSdk = ${V.compileSdk}
    defaultConfig { minSdk = ${minSdk} }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    publishing { singleVariant("release") { withSourcesJar() } }
}

kotlin { compilerOptions { jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17) } }

dependencies {
    api("org.jetbrains.kotlinx:kotlinx-serialization-json:${V.serialization}")
    api("org.jetbrains.kotlinx:kotlinx-coroutines-android:${V.coroutines}")
    api("androidx.webkit:webkit:${V.webkit}")
}

publishing {
    publications {
        register<MavenPublication>("release") {
            groupId = "${groupId}"
            artifactId = "${artifactId}"
            version = "${model.version}"
            afterEvaluate { from(components["release"]) }
            pom {
                name.set("${model.title}")
                description.set("WebView bridge for Android, generated by bridgegen from asyncapi.yaml")
                licenses { license { name.set("MIT") } }
            }
        }
    }
    repositories {
        // ./gradlew publish → <out>/maven (로컬 Maven 저장소). 사내 저장소는 여기에 추가한다.
        maven { name = "local"; url = uri(providers.gradleProperty("bridgegen.repo").getOrElse("\${rootDir}/../maven")) }
    }
}
`,
  )
  write(join(dir, 'gradle.properties'), 'android.useAndroidX=true\norg.gradle.jvmargs=-Xmx2g\nkotlin.code.style=official\n')
  write(join(dir, 'README.md'), `# ${groupId}:${artifactId}:${model.version}\n\n${model.title} Android 브릿지 라이브러리 (AAR). \`./gradlew publish\` 로 \`../maven\` 에 배포합니다.\n`)
  if (!publish) return { dir }
  const sdk = findAndroidSdk()
  const java = findJavaHome()
  if (!sdk) throw new Error('Android SDK를 찾지 못함 (ANDROID_HOME 설정 또는 --no-android-publish)')
  if (!java) throw new Error('JDK 17+를 찾지 못함 (JAVA_HOME 설정)')
  write(join(dir, 'local.properties'), `sdk.dir=${sdk}\n`)
  log('  · gradle publish (첫 실행은 의존성을 내려받아 몇 분 걸립니다)')
  run('./gradlew', ['--no-daemon', '-q', 'publishReleasePublicationToLocalRepository'], { cwd: dir, quiet: true, env: { ...process.env, JAVA_HOME: java } })
  const repo = join(out, 'maven')
  const aar = join(repo, ...groupId.split('.'), artifactId, model.version, `${artifactId}-${model.version}.aar`)
  if (!existsSync(aar)) throw new Error(`AAR이 없음: ${relative(process.cwd(), aar)}`)
  return { dir, repo, aar }
}

// ── 문서 ─────────────────────────────────────────────────────────────
export function buildDocs(model, specText, out) {
  const dir = join(out, 'docs')
  write(join(dir, 'index.html'), emitDocs(model))
  write(join(dir, 'asyncapi.yaml'), specText)
  return { dir }
}
